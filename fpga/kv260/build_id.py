#!/usr/bin/env python3
"""Revision identity of the KV260 design (read back from pe_lab, 0xA0030000).

    build_id.py info                     # JSON: the checkout's RTL revision
    build_id.py vh STAGE OUT.vh JSON     # build.sh: build_id.vh for pe_lab.v + a record

The RTL revision is the last commit that touched the RTL inputs (INPUTS
below): commits that change only docs, tests or host software keep it, so a
bitstream stays valid across them. `dirty` means an input differs from that
commit (modified, staged or untracked), so the bitstream is not exactly any
commit; build.sh refuses that unless ALLOW_DIRTY=1. The digest is the first
32 bits of the SHA-256 over the staged RTL (flow/fpga_profile.py output) and
the fabric sources, the exact bytes Vivado read.
"""
import hashlib
import json
import pathlib
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = pathlib.Path(__file__).resolve().parent
FABRIC = ["build.tcl", "kv260_top.v", "pe_spim.v", "pe_lab.v", "kv260.xdc"]
INPUTS = ["src", "flow/fpga_profile.py"] + [f"fpga/kv260/{f}" for f in FABRIC]


def git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


def info():
    return {
        "rtl_rev": git("log", "-1", "--format=%H", "--", *INPUTS),
        "head": git("rev-parse", "HEAD"),
        "dirty": bool(git("status", "--porcelain", "--untracked-files=all", "--", *INPUTS)),
    }


def digest(stage):
    h = hashlib.sha256()
    files = sorted(p for p in (stage / "rtl").rglob("*") if p.is_file())
    files += [stage / f for f in FABRIC]
    for p in files:
        h.update(str(p.relative_to(stage)).encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()[:8]


def write_vh(stage, vh, record):
    d = info()
    d["digest"] = digest(stage)
    d["build_time"] = int(time.time())
    d["build_utc"] = time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(d["build_time"]))
    pathlib.Path(vh).write_text(
        "// generated by fpga/kv260/build_id.py (build.sh): the build's identity\n"
        f"`define BUILD_RTL_REV 160'h{d['rtl_rev']}\n"
        f"`define BUILD_HEAD_REV 160'h{d['head']}\n"
        f"`define BUILD_DIRTY 1'b{int(d['dirty'])}\n"
        f"`define BUILD_TIME 32'd{d['build_time']}\n"
        f"`define BUILD_DIGEST 32'h{d['digest']}\n")
    pathlib.Path(record).write_text(json.dumps(d, indent=1) + "\n")
    return d


if __name__ == "__main__":
    if sys.argv[1:2] == ["info"]:
        print(json.dumps(info()))
    elif sys.argv[1:2] == ["vh"] and len(sys.argv) == 5:
        print(json.dumps(write_vh(pathlib.Path(sys.argv[2]), sys.argv[3], sys.argv[4])))
    else:
        sys.exit(__doc__)
