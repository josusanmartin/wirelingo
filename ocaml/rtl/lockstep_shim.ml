let mirror ~prefix wires =
  List.map wires ~f:(fun (n, w) ->
    Printf.sprintf "  wire [%d:0] %s = %s.%s;\n" (w - 1) n prefix n)
  |> String.concat
;;

let core_block ~fifo_log2 c =
  let path = Printf.sprintf "u_impl.u_core_%d" c in
  Printf.sprintf
    "    if (c == %d) begin : g_on\n\
     if (1) begin : u_core\n\
     %s\
     wire [31:0] txf_head = %s.u_fifos.txf_head;\n\
     wire [31:0] rxf_head = %s.u_fifos.rxf_head;\n\
     if (1) begin : u_fifos\n\
     if (1) begin : txf\n\
     wire [%d:0] cnt = %s.u_fifos.txf.cnt;\n\
     end\n\
     if (1) begin : rxf\n\
     wire [%d:0] cnt = %s.u_fifos.rxf.cnt;\n\
     end\n\
     end\n\
     end\n\
     end\n"
    c
    (mirror ~prefix:path core_wires)
    path
    path
    fifo_log2
    path
    fifo_log2
    path
;;

let verilog ~(cfg : Config.t) =
  let cores =
    List.init cfg.ncores ~f:(core_block ~fifo_log2:cfg.fifo_log2)
    |> String.concat ~sep:"    else\n"
  in
  Printf.sprintf
    "// Generated by ocaml/bin/gen_rtl: lockstep test scaffolding, see\n\
     // ocaml/rtl/lockstep_shim.ml. The design is %s, instance u_impl.\n\
     `default_nettype none\n\
     module pe_chip #(\n\
    \    parameter BANK_AW = 4, parameter NCORES = 4, parameter NBANKS = 4, parameter FIFO_LOG2 = 2\n\
     ) (\n\
    \    input wire clk, input wire rst_n,\n\
    \    input wire [4:0] ui_in, input wire [7:0] uio_in,\n\
    \    output wire [6:0] uo_out, output wire [7:0] uio_out, output wire [7:0] uio_oe,\n\
    \    input wire [15:0] bus_addr, input wire bus_we, input wire [31:0] bus_wdata,\n\
    \    input wire bus_commit, input wire bus_snap, input wire bus_cancel,\n\
    \    output wire [31:0] bus_rdata, output wire quad_en\n\
     );\n\
    \  initial if (BANK_AW != %d || NCORES != %d || NBANKS != %d || FIFO_LOG2 != %d) begin\n\
    \    $display(\"pe_chip_lockstep: built for BANK_AW=%d NCORES=%d NBANKS=%d FIFO_LOG2=%d\");\n\
    \    $fatal;\n\
    \  end\n\
    \  %s u_impl (.clk(clk), .rst_n(rst_n), .ui_in(ui_in), .uio_in(uio_in),\n\
    \      .uo_out(uo_out), .uio_out(uio_out), .uio_oe(uio_oe),\n\
    \      .bus_addr(bus_addr), .bus_we(bus_we), .bus_wdata(bus_wdata),\n\
    \      .bus_commit(bus_commit), .bus_snap(bus_snap), .bus_cancel(bus_cancel),\n\
    \      .bus_rdata(bus_rdata), .quad_en(quad_en));\n\
     %s\
    \  if (1) begin : u_line\n\
     %s\
    \  end\n\
    \  genvar c;\n\
    \  generate\n\
    \    for (c = 0; c < NCORES; c = c + 1) begin : g_core\n\
     %s\
    \    end\n\
    \  endgenerate\n\
     endmodule\n"
    impl_module
    (Config.bank_aw cfg)
    cfg.ncores
    cfg.nbanks
    cfg.fifo_log2
    (Config.bank_aw cfg)
    cfg.ncores
    cfg.nbanks
    cfg.fifo_log2
    impl_module
    (mirror ~prefix:"u_impl" chip_wires)
    (mirror ~prefix:"u_impl.u_line" line_wires)
    cores
;;
