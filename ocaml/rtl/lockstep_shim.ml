(* test/test_lockstep.py reads state through the Verilog's generate hierarchy
   (dut.u_chip.g_core[0].g_on.u_core.pc) and instantiates pe_chip with
   parameters (test/tb_chip.v). Generated Verilog has neither, and the tests may
   not change. So for TB=chip this module writes a pe_chip with the parameters
   and with named blocks that mirror the state as read-only wires: test
   scaffolding, outside the port. The design under test is pe_chip_hc, the
   Hardcaml pe_chip, instantiated as u_impl. *)
